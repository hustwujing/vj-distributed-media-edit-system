#!/usr/bin/env bash
set -euo pipefail

test -d wheels
case "${1:-}" in
  base)
    case "${BASE_IMAGE:-}" in *@sha256:????????????????????????????????????????????????????????????????) ;; *) echo 'BASE_IMAGE must be image@sha256:<64 hex>' >&2; exit 2;; esac
    docker build --network=none -f runtime/opensandbox/base.Dockerfile \
      --build-arg "BASE_IMAGE=$BASE_IMAGE" -t agent-runtime-base:build .
    ;;
  harnesses)
    case "${RUNTIME_BASE:-}" in *@sha256:????????????????????????????????????????????????????????????????) ;; *) echo 'RUNTIME_BASE must be image@sha256:<64 hex>' >&2; exit 2;; esac
    test -x vendor/codex
    for harness in codex claude deepseek; do
      docker build --network=none -f "runtime/opensandbox/$harness.Dockerfile" \
        --build-arg "RUNTIME_BASE=$RUNTIME_BASE" -t "agent-runtime-$harness:build" .
    done
    ;;
  *) echo 'usage: build-agent-runtime.sh base|harnesses' >&2; exit 2;;
esac
